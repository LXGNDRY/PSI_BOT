def generate_icon_snippet(name: str) -> Snippet:
    """Generate a snippet for a single icon."""
    svg_data = generate_icon_svg(name)
    template = f"""{{% comment %}}Icon: {name}{{% endcomment %}}
<svg class="icon icon--{{{{ size | default: 'medium' }}}}" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">
  <use href="#icon-{name}"></use>
</svg>
"""
    return Snippet(
        name=f"icon-{name}",
        template=template,
        params=["size"],
        styles="",  # CSS is consolidated in one file
    )


def generate_icon_svg(name: str) -> str:
    d = _icon_svg(name)
    return f'<symbol id="icon-{name}" viewBox="0 0 24 24"><path fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" d="{d}"></path></symbol>'


def generate_sprite() -> str:
    """Generate the full SVG sprite file."""
    symbols = "\n  ".join(generate_icon_svg(n) for n in ICONS)
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" style="display:none">
  {symbols}
</svg>
'''


